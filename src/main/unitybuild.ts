import { promises as fs, rmSync } from 'fs'
import { join } from 'path'
import type { BuildPhaseId, BuildReport } from '@shared/types'
import { exists } from './resolve'

/**
 * Headless Unity builds.
 *
 * Unity can't build from the command line without an editor-side method to call,
 * so when a project doesn't provide one we write a temporary editor script into
 * it, build with that, and delete it again. The script also dumps Unity's
 * BuildReport as JSON, which is what the asset analysis reads.
 */

export const INJECT_ROOT = 'GameBridge'
const INJECT_SUBDIR = join('Assets', INJECT_ROOT, 'Editor')
const INJECT_FILE = 'GameBridgeBuilder.cs'

/** Fully-qualified method Unity is told to invoke. */
export const INJECT_METHOD = 'GameBridgeGenerated.GameBridgeBuilder.BuildFromArgs'

/** Prefix our generated script logs with, so we can pick its lines out of the log. */
export const MARKER = '[GameBridge]'

const BUILD_SCRIPT = `// ---------------------------------------------------------------------------
// Generated by GameBridge for a headless build. This file is written before the
// build and deleted after it — it is safe to delete at any time, and safe to
// leave out of source control.
// ---------------------------------------------------------------------------
#if UNITY_2018_1_OR_NEWER
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace GameBridgeGenerated
{
    public static class GameBridgeBuilder
    {
        const string Tag = "${MARKER}";

        public static void BuildFromArgs()
        {
            string targetName = Arg("-gbTarget");
            string output = Arg("-gbOutput");
            string reportPath = Arg("-gbReport");
            string profilePath = Arg("-gbProfile");
            bool development = Flag("-gbDevelopment");

            try
            {
                string dir = Path.GetDirectoryName(output);
                if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);

                BuildOptions flags = development
                    ? (BuildOptions.Development | BuildOptions.AllowDebugging)
                    : BuildOptions.None;

                BuildReport report;
                string[] scenes;

                if (!string.IsNullOrEmpty(profilePath))
                {
                    // A profile carries its own target, scenes and player settings.
                    report = BuildWithProfile(profilePath, output, flags, reportPath, out scenes);
                    if (report == null) return; // BuildWithProfile already exited
                }
                else
                {
                    BuildTarget target = (BuildTarget)Enum.Parse(typeof(BuildTarget), targetName, true);
                    BuildTargetGroup group = BuildPipeline.GetBuildTargetGroup(target);

                    scenes = EnabledScenes();
                    Log("scenes=" + scenes.Length);
                    if (scenes.Length == 0)
                    {
                        Log("fatal=No enabled scenes in File > Build Settings. Add at least one scene.");
                        WriteFailure(reportPath, targetName, output, "No enabled scenes in Build Settings.");
                        EditorApplication.Exit(2);
                        return;
                    }
                    foreach (string scene in scenes) Log("scene=" + scene);

                    BuildPlayerOptions options = new BuildPlayerOptions();
                    options.scenes = scenes;
                    options.locationPathName = output;
                    options.target = target;
                    options.targetGroup = group;
                    options.options = flags;

                    Log("phase=building");
                    Log("target=" + target + " development=" + development);
                    report = BuildPipeline.BuildPlayer(options);
                }

                Log("phase=reporting");
                WriteReport(report, reportPath, scenes);
                bool ok = report.summary.result == BuildResult.Succeeded;
                Log("result=" + report.summary.result);
                Log("size=" + report.summary.totalSize);
                EditorApplication.Exit(ok ? 0 : 1);
            }
            catch (Exception e)
            {
                Log("fatal=" + e.Message);
                Debug.LogError(e);
                WriteFailure(reportPath, targetName, output, e.ToString());
                EditorApplication.Exit(3);
            }
        }

        /**
         * Unity 6 Build Profiles. Guarded so the script still compiles on older
         * editors, where the type does not exist.
         */
        static BuildReport BuildWithProfile(string profilePath, string output, BuildOptions flags, string reportPath, out string[] scenes)
        {
            scenes = new string[0];
#if UNITY_6000_0_OR_NEWER
            var profile = AssetDatabase.LoadAssetAtPath<UnityEditor.Build.Profile.BuildProfile>(profilePath);
            if (profile == null)
            {
                Log("fatal=Build profile not found at " + profilePath);
                WriteFailure(reportPath, "", output, "Build profile not found at " + profilePath);
                EditorApplication.Exit(2);
                return null;
            }

            Log("profile=" + profile.name);
            Log("phase=building");
            UnityEditor.Build.Profile.BuildProfile.SetActiveBuildProfile(profile);

            var options = new BuildPlayerWithProfileOptions();
            options.buildProfile = profile;
            options.locationPathName = output;
            options.options = flags;

            scenes = ProfileScenes(profile);
            foreach (string scene in scenes) Log("scene=" + scene);

            BuildReport report = BuildPipeline.BuildPlayer(options);
            return report;
#else
            Log("fatal=Build profiles need Unity 6 or newer.");
            WriteFailure(reportPath, "", output, "Build profiles need Unity 6 or newer.");
            EditorApplication.Exit(2);
            return null;
#endif
        }

#if UNITY_6000_0_OR_NEWER
        /**
         * Which scenes a profile builds: its own list when it overrides the
         * global one, otherwise Build Settings. The cleanup view needs this —
         * a build report lists packed assets, and scenes are not among them.
         */
        static string[] ProfileScenes(UnityEditor.Build.Profile.BuildProfile profile)
        {
            if (profile.overrideGlobalScenes && profile.scenes != null)
            {
                List<string> list = new List<string>();
                foreach (EditorBuildSettingsScene scene in profile.scenes)
                {
                    if (scene.enabled && !string.IsNullOrEmpty(scene.path)) list.Add(scene.path);
                }
                return list.ToArray();
            }
            return EnabledScenes();
        }
#endif

        static void Log(string message)
        {
            Console.WriteLine(Tag + " " + message);
            Console.Out.Flush();
        }

        static string Arg(string name)
        {
            string[] args = Environment.GetCommandLineArgs();
            for (int i = 0; i < args.Length - 1; i++)
            {
                if (string.Equals(args[i], name, StringComparison.OrdinalIgnoreCase)) return args[i + 1];
            }
            return "";
        }

        static bool Flag(string name)
        {
            foreach (string a in Environment.GetCommandLineArgs())
            {
                if (string.Equals(a, name, StringComparison.OrdinalIgnoreCase)) return true;
            }
            return false;
        }

        static string[] EnabledScenes()
        {
            List<string> list = new List<string>();
            foreach (EditorBuildSettingsScene scene in EditorBuildSettings.scenes)
            {
                if (scene.enabled && !string.IsNullOrEmpty(scene.path) && File.Exists(scene.path))
                {
                    list.Add(scene.path);
                }
            }
            return list.ToArray();
        }

        static void WriteFailure(string path, string platform, string output, string reason)
        {
            if (string.IsNullOrEmpty(path)) return;
            StringBuilder sb = new StringBuilder();
            sb.Append("{\\"result\\":\\"Failed\\",\\"platform\\":\\"").Append(Esc(platform));
            sb.Append("\\",\\"outputPath\\":\\"").Append(Esc(output));
            sb.Append("\\",\\"totalBytes\\":0,\\"totalSeconds\\":0,\\"errors\\":1,\\"warnings\\":0,");
            sb.Append("\\"steps\\":[],\\"assets\\":[],\\"scenes\\":[],\\"messages\\":[{\\"type\\":\\"Error\\",\\"content\\":\\"");
            sb.Append(Esc(reason)).Append("\\"}]}");
            SafeWrite(path, sb.ToString());
        }

        static void WriteReport(BuildReport report, string path, string[] scenes)
        {
            if (string.IsNullOrEmpty(path)) return;
            BuildSummary summary = report.summary;
            StringBuilder sb = new StringBuilder(64 * 1024);

            sb.Append("{");
            Field(sb, "result", summary.result.ToString());
            Field(sb, "platform", summary.platform.ToString());
            Field(sb, "outputPath", summary.outputPath);
            sb.Append("\\"totalBytes\\":").Append(summary.totalSize.ToString(CultureInfo.InvariantCulture)).Append(",");
            sb.Append("\\"totalSeconds\\":").Append(summary.totalTime.TotalSeconds.ToString("F2", CultureInfo.InvariantCulture)).Append(",");
            sb.Append("\\"errors\\":").Append(summary.totalErrors.ToString(CultureInfo.InvariantCulture)).Append(",");
            sb.Append("\\"warnings\\":").Append(summary.totalWarnings.ToString(CultureInfo.InvariantCulture)).Append(",");

            // Steps, with their own error/warning counts.
            List<string> messages = new List<string>();
            sb.Append("\\"steps\\":[");
            bool firstStep = true;
            foreach (BuildStep step in report.steps)
            {
                int errors = 0;
                int warnings = 0;
                foreach (BuildStepMessage m in step.messages)
                {
                    if (m.type == LogType.Error || m.type == LogType.Exception || m.type == LogType.Assert) errors++;
                    else if (m.type == LogType.Warning) warnings++;
                    if (m.type != LogType.Log && messages.Count < 60)
                    {
                        messages.Add("{\\"type\\":\\"" + Esc(m.type.ToString()) + "\\",\\"content\\":\\"" + Esc(Trim(m.content, 400)) + "\\"}");
                    }
                }
                if (!firstStep) sb.Append(",");
                firstStep = false;
                sb.Append("{");
                Field(sb, "name", step.name);
                sb.Append("\\"seconds\\":").Append(step.duration.TotalSeconds.ToString("F3", CultureInfo.InvariantCulture)).Append(",");
                sb.Append("\\"depth\\":").Append(((int)step.depth).ToString(CultureInfo.InvariantCulture)).Append(",");
                sb.Append("\\"errors\\":").Append(errors.ToString(CultureInfo.InvariantCulture)).Append(",");
                sb.Append("\\"warnings\\":").Append(warnings.ToString(CultureInfo.InvariantCulture));
                sb.Append("}");
            }
            sb.Append("],");

            sb.Append("\\"messages\\":[").Append(string.Join(",", messages.ToArray())).Append("],");

            sb.Append("\\"scenes\\":[");
            for (int i = 0; i < scenes.Length; i++)
            {
                if (i > 0) sb.Append(",");
                sb.Append("\\"").Append(Esc(scenes[i])).Append("\\"");
            }
            sb.Append("],");

            // Packed assets, merged across output files and capped to the big ones.
            Dictionary<string, ulong> sizes = new Dictionary<string, ulong>();
            Dictionary<string, string> types = new Dictionary<string, string>();
            foreach (PackedAssets packed in report.packedAssets)
            {
                foreach (PackedAssetInfo info in packed.contents)
                {
                    string assetPath = info.sourceAssetPath;
                    if (string.IsNullOrEmpty(assetPath)) continue;
                    ulong current;
                    sizes.TryGetValue(assetPath, out current);
                    sizes[assetPath] = current + info.packedSize;
                    if (!types.ContainsKey(assetPath))
                    {
                        types[assetPath] = info.type == null ? "" : info.type.Name;
                    }
                }
            }
            List<KeyValuePair<string, ulong>> ordered = new List<KeyValuePair<string, ulong>>(sizes);
            ordered.Sort(delegate (KeyValuePair<string, ulong> a, KeyValuePair<string, ulong> b)
            {
                return b.Value.CompareTo(a.Value);
            });

            // Every packed asset, not just the big ones: the cleanup view needs
            // the full set to tell what the project has that the build didn't use.
            sb.Append("\\"assets\\":[");
            int count = ordered.Count;
            for (int i = 0; i < count; i++)
            {
                if (i > 0) sb.Append(",");
                sb.Append("{");
                Field(sb, "path", ordered[i].Key);
                Field(sb, "type", types[ordered[i].Key]);
                sb.Append("\\"bytes\\":").Append(ordered[i].Value.ToString(CultureInfo.InvariantCulture));
                sb.Append("}");
            }
            sb.Append("]}");

            SafeWrite(path, sb.ToString());
        }

        static void SafeWrite(string path, string contents)
        {
            try
            {
                string dir = Path.GetDirectoryName(path);
                if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
                File.WriteAllText(path, contents);
            }
            catch (Exception e)
            {
                Log("fatal=Could not write report: " + e.Message);
            }
        }

        static void Field(StringBuilder sb, string name, string value)
        {
            sb.Append("\\"").Append(name).Append("\\":\\"").Append(Esc(value)).Append("\\",");
        }

        static string Trim(string s, int max)
        {
            if (s == null) return "";
            return s.Length <= max ? s : s.Substring(0, max) + "…";
        }

        static string Esc(string s)
        {
            if (string.IsNullOrEmpty(s)) return "";
            StringBuilder sb = new StringBuilder(s.Length + 8);
            foreach (char c in s)
            {
                switch (c)
                {
                    case '"': sb.Append("\\\\\\""); break;
                    case '\\\\': sb.Append("\\\\\\\\"); break;
                    case '\\b': sb.Append("\\\\b"); break;
                    case '\\f': sb.Append("\\\\f"); break;
                    case '\\n': sb.Append("\\\\n"); break;
                    case '\\r': sb.Append("\\\\r"); break;
                    case '\\t': sb.Append("\\\\t"); break;
                    default:
                        if (c < ' ') sb.Append("\\\\u").Append(((int)c).ToString("x4"));
                        else sb.Append(c);
                        break;
                }
            }
            return sb.ToString();
        }
    }
}
#else
#error GameBridge headless builds need Unity 2018.1 or newer.
#endif
`

export interface Injection {
  /** Folder that must be deleted to undo the injection (with its .meta). */
  removeDir?: string
  /** File written when the folders already existed. */
  removeFile?: string
}

/**
 * Write the build script into the project. Only the directories we create are
 * recorded for removal, so an existing Assets/GameBridge folder is left alone.
 */
export async function injectBuildScript(projectPath: string): Promise<Injection> {
  const levels = [
    join(projectPath, 'Assets'),
    join(projectPath, 'Assets', INJECT_ROOT),
    join(projectPath, 'Assets', INJECT_ROOT, 'Editor')
  ]

  let created: string | undefined
  for (const dir of levels) {
    if (!(await exists(dir))) {
      created ??= dir
      await fs.mkdir(dir, { recursive: true })
    }
  }

  const file = join(projectPath, INJECT_SUBDIR, INJECT_FILE)
  await fs.writeFile(file, BUILD_SCRIPT, 'utf-8')
  return created ? { removeDir: created } : { removeFile: file }
}

/**
 * Undo an injection, including the .meta files Unity generates alongside it.
 * A cancelled build leaves Unity briefly holding the folder, so retry once.
 */
export async function cleanupBuildScript(injection: Injection | undefined): Promise<void> {
  if (!injection) return
  const remove = async (path: string, dir: boolean, attempt = 0): Promise<void> => {
    try {
      if (dir) await fs.rm(path, { recursive: true, force: true })
      else await fs.rm(path, { force: true })
      await fs.rm(path + '.meta', { force: true })
    } catch {
      if (attempt < 2) {
        await new Promise((r) => setTimeout(r, 1500))
        return remove(path, dir, attempt + 1)
      }
      /* still locked — leave it; the next build overwrites the file in place */
    }
  }
  if (injection.removeDir) await remove(injection.removeDir, true)
  if (injection.removeFile) await remove(injection.removeFile, false)
}

/** Blocking variant for app shutdown, where we can't await anything. */
export function cleanupBuildScriptSync(injection: Injection | undefined): void {
  if (!injection) return
  const remove = (path: string, dir: boolean): void => {
    try {
      rmSync(path, { recursive: dir, force: true })
      rmSync(path + '.meta', { force: true })
    } catch {
      /* best effort */
    }
  }
  if (injection.removeDir) remove(injection.removeDir, true)
  if (injection.removeFile) remove(injection.removeFile, false)
}

/* ------------------------------------------------------------- log phases */

/** Weighted progress band per phase — Unity reports no real percentage. */
const PHASE_RANGE: Record<string, [number, number]> = {
  starting: [0, 5],
  switching: [5, 12],
  importing: [12, 40],
  compiling: [40, 62],
  building: [62, 95],
  reporting: [95, 99]
}

const PHASE_ORDER: BuildPhaseId[] = [
  'starting',
  'switching',
  'importing',
  'compiling',
  'building',
  'reporting'
]

export interface PhaseSnapshot {
  phase: BuildPhaseId
  activity: string
  percent: number
  imported: number
  errors: number
  warnings: number
}

/**
 * Reads Unity's batchmode log and works out what the editor is actually doing.
 * Returns a snapshot when something the UI cares about changed, else null.
 */
export function createPhaseTracker(): (line: string) => PhaseSnapshot | null {
  let phase: BuildPhaseId = 'starting'
  let activity = 'Starting Unity…'
  let imported = 0
  let errors = 0
  let warnings = 0
  let ticks = 0
  let lastPercent = 0

  const enter = (next: BuildPhaseId): void => {
    // Never go backwards: a late asset import shouldn't undo "building".
    if (PHASE_ORDER.indexOf(next) > PHASE_ORDER.indexOf(phase)) {
      phase = next
      ticks = 0
    }
  }

  const percent = (): number => {
    const range = PHASE_RANGE[phase]
    if (!range) return lastPercent
    const [lo, hi] = range
    const p = Math.round(lo + (hi - lo) * (1 - Math.exp(-ticks / 25)))
    lastPercent = Math.max(lastPercent, p)
    return lastPercent
  }

  return (line: string): PhaseSnapshot | null => {
    const before = { phase, activity, imported, errors, warnings }
    ticks++

    // Our own markers are the most reliable signal we have.
    if (line.includes(MARKER)) {
      const marker = line.slice(line.indexOf(MARKER) + MARKER.length).trim()
      if (marker.startsWith('phase=building')) {
        enter('building')
        activity = 'Building player'
      } else if (marker.startsWith('phase=reporting')) {
        enter('reporting')
        activity = 'Writing build report'
      } else if (marker.startsWith('scenes=')) {
        activity = `Building ${marker.slice(7)} scene(s)`
      } else if (marker.startsWith('fatal=')) {
        errors++
        activity = marker.slice(6)
      }
    } else if (/^Initialize engine version|^Unity Editor version/i.test(line)) {
      activity = line.trim()
    } else if (/switching active build target|Switching to .* platform/i.test(line)) {
      enter('switching')
      activity = 'Switching build target (this reimports assets)'
    } else if (/^Start importing |^Done importing asset:|^\s*Import(ing)? asset/i.test(line)) {
      enter('importing')
      // Unity logs both "Start importing" and "Done importing" for each asset —
      // only count one of them or the total comes out doubled.
      if (!/^Done importing/i.test(line)) imported++
      const m = line.match(/'([^']+)'|Start importing (\S+)/)
      const asset = m?.[1] ?? m?.[2]
      activity = asset ? `Importing ${asset}` : 'Importing assets'
    } else if (/Asset Pipeline Refresh|AssetDatabase\.Refresh/i.test(line)) {
      enter('importing')
      activity = 'Refreshing the asset database'
    } else if (/^- Starting compile |Begin MonoManager|Compiling scripts/i.test(line)) {
      enter('compiling')
      const dll = line.match(/([\w.-]+\.dll)/)?.[1]
      activity = dll ? `Compiling ${dll}` : 'Compiling scripts'
    } else if (/^Compiling shader/i.test(line)) {
      activity = line.replace(/^Compiling shader\s*/i, 'Compiling shader ').trim()
    } else if (/^DisplayProgressbar:/i.test(line)) {
      activity = line.replace(/^DisplayProgressbar:\s*/i, '').trim()
      if (/build|player|scene|packag/i.test(activity)) enter('building')
    } else if (/Building Player|BuildPlayer|Build Player/i.test(line)) {
      enter('building')
      activity = 'Building player'
    } else if (/^\*\*\* Completed '([^']+)'/.test(line)) {
      const step = line.match(/^\*\*\* Completed '([^']+)'/)?.[1]
      if (step) activity = `Finished ${step}`
    } else if (/Uncompressed usage by category|^Build Report/i.test(line)) {
      enter('reporting')
      activity = 'Collecting the build report'
    }

    if (/\berror CS\d+|BuildFailedException|Error building Player|^Fatal Error|UnauthorizedAccessException/i.test(line)) {
      errors++
    } else if (/\bwarning CS\d+/i.test(line)) {
      warnings++
    }

    const changed =
      before.phase !== phase ||
      before.activity !== activity ||
      before.errors !== errors ||
      before.warnings !== warnings ||
      // Don't emit for every single imported asset; every 25 is plenty.
      (imported !== before.imported && imported % 25 === 0)

    if (!changed) return null
    return { phase, activity, percent: percent(), imported, errors, warnings }
  }
}

/* ------------------------------------------------------------- the report */

/** Read the JSON our injected script wrote. Returns undefined if it never ran. */
export async function readBuildReport(path: string): Promise<BuildReport | undefined> {
  try {
    const raw = await fs.readFile(path, 'utf-8')
    const parsed = JSON.parse(raw) as BuildReport
    return {
      result: parsed.result ?? 'Unknown',
      platform: parsed.platform ?? '',
      outputPath: parsed.outputPath ?? '',
      totalBytes: Number(parsed.totalBytes) || 0,
      totalSeconds: Number(parsed.totalSeconds) || 0,
      errors: Number(parsed.errors) || 0,
      warnings: Number(parsed.warnings) || 0,
      steps: Array.isArray(parsed.steps) ? parsed.steps : [],
      // Trimmed for the history file; readPackedAssetPaths reads the full list.
      assets: Array.isArray(parsed.assets) ? parsed.assets.slice(0, 500) : [],
      messages: Array.isArray(parsed.messages) ? parsed.messages : []
    }
  } catch {
    return undefined
  }
}

/**
 * What the build actually contained: every packed asset path, plus the scenes
 * it was told to build. Scenes are compiled into level files rather than packed
 * assets, so without that list every scene in the project looks unused.
 *
 * Lower-cased with forward slashes for comparison against files on disk;
 * built-in assets carry no project path and are dropped.
 */
export async function readBuildContents(
  path: string
): Promise<{ assets: Set<string>; scenes: Set<string> }> {
  const assets = new Set<string>()
  const scenes = new Set<string>()
  try {
    const parsed = JSON.parse(await fs.readFile(path, 'utf-8')) as {
      assets?: { path?: string }[]
      scenes?: string[]
    }
    for (const a of parsed.assets ?? []) {
      const p = a.path?.trim()
      if (!p || !/^(Assets|Packages)\//i.test(p)) continue
      assets.add(p.replace(/\\/g, '/').toLowerCase())
    }
    for (const scene of parsed.scenes ?? []) {
      if (scene?.trim()) scenes.add(scene.replace(/\\/g, '/').toLowerCase())
    }
  } catch {
    /* no report for this build */
  }
  return { assets, scenes }
}
